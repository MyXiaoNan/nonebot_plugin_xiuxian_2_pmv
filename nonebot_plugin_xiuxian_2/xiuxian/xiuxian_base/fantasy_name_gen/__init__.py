def generate_dao_name():
    """生成一个修仙风格的道号"""
    style = random.randint(1, 5)
    
    if style == 1:  # 单字 + 后缀
        name = random.choice(dao_middle) + random.choice(dao_suffixes)
    elif style == 2:  # 前缀 + 单字
        name = random.choice(dao_prefixes) + random.choice(dao_middle)
    elif style == 3:  # 前缀 + 单字 + 后缀
        name = random.choice(dao_prefixes) + random.choice(dao_middle) + random.choice(dao_suffixes)
    elif style == 4:  # 双字词组 + 后缀
        name = random.choice(dao_double_words) + random.choice(dao_suffixes)
    else:  # 单字 + 单字 + 后缀
        name = random.choice(dao_middle) + random.choice(dao_middle) + random.choice(dao_suffixes)
    
    return name

